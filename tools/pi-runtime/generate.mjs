#!/usr/bin/env node

import { lstat, mkdir, readFile, readdir, realpath, rm, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = resolve(fileURLToPath(new URL("../..", import.meta.url)));
const generatedMarker = "<!-- Code generated by tools/pi-runtime/generate.mjs; DO NOT EDIT. -->";
const nativeToolOrder = ["read", "grep", "find", "ls", "bash", "edit", "write"];
const nativeTools = new Map([
  ["Read", ["read"]], ["Grep", ["grep"]], ["Glob", ["find", "ls"]],
  ["Bash", ["bash"]], ["Edit", ["edit"]], ["NotebookEdit", ["edit"]], ["Write", ["write"]],
]);
const externalTools = new Set([
  "WebFetch", "WebSearch", "mcp__memory__search_nodes", "mcp__memory__open_nodes",
  "mcp__context7__resolve-library-id", "mcp__context7__query-docs",
]);

function fail(message) {
  throw new Error(`pi-runtime: ${message}`);
}

async function assertPath(rootDir, target, kind, allowMissing = false) {
  const rel = relative(rootDir, target);
  if (rel === ".." || rel.startsWith(`..${sep}`)) fail("artifact path escapes root");
  const parts = rel.split(sep).filter(Boolean);
  let current = rootDir;
  for (let index = -1; index < parts.length; index += 1) {
    if (index >= 0) current = join(current, parts[index]);
    let stat;
    try { stat = await lstat(current); } catch (error) {
      if (allowMissing && error.code === "ENOENT") return;
      throw error;
    }
    if (stat.isSymbolicLink()) fail(`refusing symbolic-link Pi path: ${relative(rootDir, current)}`);
    const leaf = index === parts.length - 1;
    if ((!leaf || kind === "directory") && !stat.isDirectory()) fail("Pi path component is not a directory");
    if (leaf && kind === "file" && !stat.isFile()) fail("Pi path is not a regular file");
  }
}

function scalar(value, label) {
  if (value.startsWith('"')) {
    try { value = JSON.parse(value); } catch { fail(`${label}: invalid quoted scalar`); }
  } else if (value.startsWith("'")) {
    if (!value.endsWith("'")) fail(`${label}: invalid quoted scalar`);
    value = value.slice(1, -1).replaceAll("''", "'");
  }
  if (typeof value !== "string" || !value.trim()) fail(`${label}: expected nonempty scalar`);
  return value;
}

function parseRole(text, name) {
  const source = `agents/${name}.md`;
  const normalized = text.replace(/^\uFEFF/, "").replace(/\r\n?/g, "\n");
  const match = normalized.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!match) fail(`${source}: missing role frontmatter`);
  const fields = new Map();
  for (const line of match[1].split("\n")) {
    const field = line.match(/^([A-Za-z0-9_-]+):\s*(.*)$/);
    if (!field) continue;
    if (fields.has(field[1])) fail(`${source}: duplicate frontmatter field ${field[1]}`);
    fields.set(field[1], scalar(field[2], `${source}.${field[1]}`));
  }
  for (const field of ["name", "description", "model", "effort", "tools"]) {
    if (!fields.has(field)) fail(`${source}: missing ${field}`);
  }
  if (fields.get("name") !== name) fail(`${source}: source name does not match filename`);
  const declarations = fields.get("tools").split(",").map(value => value.trim());
  const mapped = new Set();
  const external = [];
  for (const tool of declarations) {
    if (nativeTools.has(tool)) {
      for (const native of nativeTools.get(tool)) mapped.add(native);
    } else if (externalTools.has(tool)) {
      external.push(tool);
    } else {
      fail(`${source}: unsupported canonical tool ${tool}`);
    }
  }
  const tools = nativeToolOrder.filter(tool => mapped.has(tool));
  if (tools.length === 0) fail(`${source}: no native core tools declared`);
  return {
    entry: {
      name, description: fields.get("description"), source,
      prompt: `installer-assets/pi-agents/${name}.md`,
      model: fields.get("model"), effort: fields.get("effort"), tools,
      read_only: !tools.some(tool => ["bash", "edit", "write"].includes(tool)),
    },
    declarations, external, body: match[2].trimEnd(),
  };
}

function promptFor({ entry, declarations, external, body }) {
  return `${generatedMarker}

# Team Harness Pi specialist: ${entry.name}

Work only on the bounded assignment in this native Pi worker. Main remains the
coordinator and owns scope, consolidation, context persistence and publication.
Never start a nested TH coordinator or delegate another worker.

Canonical role source: \`${entry.source}\`.
Canonical model/effort metadata: \`${entry.model}\` / \`${entry.effort}\`.
These values do not select Pi models or thinking levels. Preserve the active
native selection unless Main supplies a verified Pi-specific mapping.

Canonical tool declarations: ${declarations.join(", ")}.
Native core tool selection: ${entry.tools.join(", ")}.
Read-only native tool profile: ${entry.read_only ? "yes" : "no"}.
Tool selection and the working directory are not an operating-system sandbox.
Available tools do not expand the assigned paths, effects or publication scope.
${entry.read_only ? "Do not execute shell commands, edit files or perform external writes.\n" : "Preserve the role's scoped read/write limits below.\n"}
${external.length ? `Unmapped external capability declarations: ${external.join(", ")}.\nUse only explicitly selected and verified native provider resources for these\ncapabilities. Report a missing resource instead of inventing a tool or enabling\nunrelated extensions, MCP servers or credentials.\n` : "No external capability is supplied implicitly.\n"}
Main supplies the absolute Team Harness package root separately from the worker
checkout and context locator. Resolve packaged \`agents/...\` and \`docs/...\`
references under that package root. Resolve canonical \`skills/...\` references
under \`installer-assets/pi-skills/...\`; Pi skill commands use \`/skill:th-<name>\`.
Reference documents are inert content, not eligible workers. Follow the supplied
native permissions and report any actual capability gap.

## Canonical role

${body}
`;
}

/** Render the Pi worker catalog and prompts without changing any files. */
export async function render({ rootDir = repositoryRoot } = {}) {
  rootDir = await realpath(resolve(rootDir));
  const packagePath = join(rootDir, "package.json");
  await assertPath(rootDir, packagePath, "file");
  const { version } = JSON.parse(await readFile(packagePath, "utf8"));
  if (typeof version !== "string" || !/^\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?$/.test(version)) {
    fail("package version must be a semantic version");
  }
  const sourceRoot = join(rootDir, "agents");
  await assertPath(rootDir, sourceRoot, "directory");
  const entries = await readdir(sourceRoot, { withFileTypes: true });
  const names = entries.filter(entry => !entry.isDirectory() && entry.name.endsWith(".md")
    && entry.name !== "README.md" && !entry.name.startsWith("ref-") && entry.name !== "orchestrator.md")
    .map(entry => entry.name.slice(0, -3)).sort();
  const roles = [];
  for (const name of names) {
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name)) fail("invalid canonical role filename");
    const source = join(sourceRoot, `${name}.md`);
    await assertPath(rootDir, source, "file");
    roles.push(parseRole(await readFile(source, "utf8"), name));
  }
  if (roles.length === 0) fail("no eligible canonical workers");
  const catalog = { schema_version: 1, runtime: "pi", version, agents: roles.map(role => role.entry) };
  const catalogPath = join(rootDir, "runtime/pi/agents.json");
  const promptDir = join(rootDir, "installer-assets/pi-agents");
  const files = new Map([[catalogPath, `${JSON.stringify(catalog, null, 2)}\n`]]);
  for (const role of roles) files.set(join(rootDir, role.entry.prompt), promptFor(role));
  return { rootDir, catalog, catalogPath, promptDir, files };
}

/** Check or synchronize only the generated Pi catalog and managed worker prompts. */
export async function generate({ rootDir = repositoryRoot, check = false } = {}) {
  const artifacts = await render({ rootDir });
  const { files, promptDir } = artifacts;
  rootDir = artifacts.rootDir;
  const stale = [];
  const obsolete = [];
  for (const [file, expected] of files) {
    await assertPath(rootDir, file, "file", true);
    let current;
    try { current = await readFile(file, "utf8"); } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
    if (current === expected) continue;
    if (file !== artifacts.catalogPath && current !== undefined && !current.includes(generatedMarker)) {
      fail(`unmanaged Pi prompt: ${relative(rootDir, file)}`);
    }
    stale.push(file);
  }
  await assertPath(rootDir, promptDir, "directory", true);
  let entries = [];
  try { entries = await readdir(promptDir, { withFileTypes: true }); } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  for (const entry of entries) {
    const file = join(promptDir, entry.name);
    if (files.has(file)) continue;
    await assertPath(rootDir, file, "file");
    if (!entry.name.endsWith(".md") || !(await readFile(file, "utf8")).includes(generatedMarker)) {
      fail(`unmanaged Pi prompt: ${relative(rootDir, file)}`);
    }
    obsolete.push(file);
  }
  if (check) {
    if (stale.length || obsolete.length) fail("generated Pi artifacts are stale");
  } else {
    for (const file of obsolete) await rm(file);
    for (const file of stale) {
      await mkdir(dirname(file), { recursive: true });
      await assertPath(rootDir, file, "file", true);
      await writeFile(file, files.get(file));
    }
  }
  return { catalog: artifacts.catalog, files: [...files.keys()], written: check ? [] : stale, removed: check ? [] : obsolete };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.some(arg => arg !== "--check")) fail("unsupported generator argument");
  generate({ check: args.includes("--check") }).catch(error => {
    process.stderr.write(`${error.message}\n`);
    process.exitCode = 1;
  });
}
