async function walkFiles(base, current = base, { symbolicLinks = "reject" } = {}) {
  const result = new Map();
  let entries;
  try {
    entries = await readdir(current, { withFileTypes: true });
  } catch (error) {
    if (error?.code === "ENOENT") return result;
    throw error;
  }
  entries.sort((a, b) => a.name.localeCompare(b.name));
  for (const entry of entries) {
    const absolute = join(current, entry.name);
    const rel = relative(base, absolute).split(sep).join("/");
    const stat = await lstat(absolute);
    if (stat.isSymbolicLink()) {
      if (symbolicLinks === "include") {
        // Keep the link as an entry for ownership classification, but never
        // follow it. Source trees and guarded destinations still use the
        // default rejection mode.
        result.set(rel, null);
        continue;
      }
      throw new Error(`refusing symbolic link: ${absolute}`);
    }
    if (stat.isDirectory()) {
      if (entry.name === "__pycache__" || entry.name === "node_modules" || entry.name === ".venv") continue;
      for (const [child, bytes] of await walkFiles(base, absolute, { symbolicLinks })) {
        result.set(child, bytes);
      }
    } else if (stat.isFile() && !entry.name.endsWith(".pyc")) {
      result.set(rel, await readFile(absolute));
    }
  }
  return result;
}

async function canonicalNames(rootDir) {
  const sourceRoot = join(rootDir, "skills");
  const entries = await readdir(sourceRoot, { withFileTypes: true });
  const names = [];
  for (const entry of entries) {
    if (!entry.isDirectory() || !namePattern.test(entry.name)) continue;
    try {
      const stat = await lstat(join(sourceRoot, entry.name, "SKILL.md"));
      if (stat.isFile()) names.push(entry.name);
    } catch (error) {
      if (error?.code !== "ENOENT") throw error;
    }
  }
  return names.sort();
}

async function expectedProjection(rootDir, name, runtime) {
  const sourceDir = join(rootDir, "skills", name);
  const sourceFiles = await walkFiles(sourceDir);
  const canonicalBytes = sourceFiles.get("SKILL.md");
  if (!canonicalBytes) throw new Error(`missing canonical skill: ${name}`);
  const canonical = parseCanonicalSkill(canonicalBytes, name);
  const expected = new Map([
    ["SKILL.md", Buffer.from(runtime === "pi" ? await renderPiAdapter(rootDir, name, canonical) : renderAdapter(name, canonical, runtime))],
    ["canonical.md", Buffer.from(`${projectSkillLinks(canonical.body, runtime)}\n`)],
  ]);
  if (runtime === "codex") {
    expected.set("agents/openai.yaml", Buffer.from(renderOpenAI(name, canonical)));
  }
  for (const [rel, bytes] of sourceFiles) {
    if (rel === "SKILL.md" || rel === "agents/openai.yaml") continue;
    expected.set(rel, runtime === "opencode" && rel.endsWith(".md")
      ? Buffer.from(projectSkillLinks(bytes.toString("utf8"), runtime))
      : bytes);
  }
  return expected;
}

async function isGenerated(targetDir) {
  try {
    const skill = await readFile(join(targetDir, "SKILL.md"), "utf8");
    return skill.includes(generatedMarker);
  } catch (error) {
    if (error?.code === "ENOENT") return false;
    throw error;
  }
}

async function projectionMatches(targetDir, expected) {
  const actual = await walkFiles(targetDir);
  if (actual.size !== expected.size) return false;
  for (const [rel, bytes] of expected) {
    if (!actual.get(rel)?.equals(bytes)) return false;
  }
  return true;
}

async function syncProjection({ check, rootDir, names, runtime, targetRoot, overrides }) {
  if (runtime === "pi") await assertSafeDestinationPath(rootDir, targetRoot, "directory");
  for (const override of overrides) {
    if (!names.includes(override)) throw new Error(`${runtime} override has no canonical skill: ${override}`);
  }

  let stale = false;
  for (const name of names) {
    if (overrides.has(name)) continue;
    const targetDir = join(targetRoot, projectedSkillName(name, runtime));
    if (runtime === "pi") await assertSafeDestinationPath(rootDir, targetDir, "directory");
    const expected = await expectedProjection(rootDir, name, runtime);
    if (await projectionMatches(targetDir, expected)) continue;
    stale = true;
    if (check) {
      process.stderr.write(`stale ${runtime} skill: ${name}\n`);
      continue;
    }
    try {
      const stat = await lstat(targetDir);
      if (stat.isSymbolicLink() || !stat.isDirectory() || !(await isGenerated(targetDir))) {
        throw new Error(`refusing to replace unmanaged ${runtime} skill: ${targetDir}`);
      }
      await rm(targetDir, { recursive: true });
    } catch (error) {
      if (error?.code !== "ENOENT") throw error;
    }
    for (const [rel, bytes] of expected) {
      const target = join(targetDir, rel);
      await mkdir(dirname(target), { recursive: true });
      await writeFile(target, bytes);
    }
  }

  let targetEntries;
  try { targetEntries = await readdir(targetRoot, { withFileTypes: true }); } catch (error) {
    if (runtime !== "pi" || error.code !== "ENOENT") throw error;
    targetEntries = [];
  }
  const projectedNames = new Set(names.map(name => projectedSkillName(name, runtime)));
  for (const entry of targetEntries) {
    if (!entry.isDirectory() || projectedNames.has(entry.name)) continue;
    const targetDir = join(targetRoot, entry.name);
    if (!(await isGenerated(targetDir))) continue;
    stale = true;
    if (check) process.stderr.write(`stale generated skill: ${entry.name}\n`);
    else await rm(targetDir, { recursive: true });
  }

  if (check && stale) throw new Error(`${runtime} skill projections are stale`);
  return names.filter(name => !overrides.has(name));
}

