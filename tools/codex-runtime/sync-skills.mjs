async function syncSetupAsset({ check, rootDir, name, executable, directory }) {
  const source = join(rootDir, "skills/setup", directory, name);
  const [bytes, sourceStat] = await Promise.all([readFile(source), lstat(source)]);
  // Git records the owner execute bit; other permission bits depend on umask.
  // Windows does not expose that bit, so content remains its portable check.
  if (executable && process.platform !== "win32" && (sourceStat.mode & 0o100) === 0) {
    throw new Error(`shared setup asset source is not executable: ${relative(rootDir, source)}`);
  }
  const targets = [
    join(rootDir, "plugins/team-harness/skills/setup", directory, name),
    join(rootDir, "installer-assets/opencode-skills/setup", directory, name),
  ];
  let stale = false;
  for (const target of targets) {
    let current;
    let currentMode;
    try {
      const [bytesAtTarget, targetStat] = await Promise.all([
        readFile(target),
        lstat(target),
      ]);
      current = bytesAtTarget;
      currentMode = targetStat.mode & 0o777;
    } catch (error) {
      if (error?.code !== "ENOENT") throw error;
    }
    const bytesMatch = current?.equals(bytes) ?? false;
    const modeMatches = process.platform === "win32" || ((currentMode & 0o100) !== 0) === executable;
    if (bytesMatch && modeMatches) continue;
    stale = true;
    if (check) {
      const drift = [!bytesMatch && "content", !modeMatches && "mode"]
        .filter(Boolean)
        .join("+");
      process.stderr.write(`stale shared setup asset (${drift}): ${relative(rootDir, target)}\n`);
      continue;
    }
    await mkdir(dirname(target), { recursive: true });
    const mode = executable ? 0o755 : 0o644;
    if (!bytesMatch) await writeFile(target, bytes, { mode });
    await chmod(target, mode);
  }
  if (check && stale) throw new Error("shared setup assets are stale");
}

