function yamlString(value) {
  return JSON.stringify(value);
}

function humanize(name) {
  return name.split("-").map(part => part[0].toUpperCase() + part.slice(1)).join(" ");
}

function parseCanonicalSkill(bytes, expectedName) {
  const text = bytes.toString("utf8").replace(/^\uFEFF/, "").replace(/\r\n?/g, "\n");
  const match = text.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!match) throw new Error(`invalid frontmatter: skills/${expectedName}/SKILL.md`);
  const fields = new Map();
  for (const line of match[1].split("\n")) {
    const field = line.match(/^([a-zA-Z0-9_-]+):\s*(.*)$/);
    if (!field) continue;
    let value = field[2].trim();
    if (value.startsWith('"') && value.endsWith('"')) value = value.slice(1, -1);
    fields.set(field[1], value);
  }
  if (fields.get("name") !== expectedName) {
    throw new Error(`skill name mismatch: ${expectedName} != ${fields.get("name")}`);
  }
  const description = fields.get("description");
  if (!description) throw new Error(`missing description: skills/${expectedName}/SKILL.md`);
  return {
    body: match[2].trimEnd(),
    description,
    explicitOnly: fields.get("disable-model-invocation") === "true",
  };
}

function projectedSkillName(name, runtime) {
  // OpenCode has a flat skill namespace; leave the upstream Sentry name intact.
  return runtime === "opencode" && name === "find-bugs" ? "th-find-bugs" : name;
}

function projectSkillLinks(markdown, runtime) {
  if (runtime !== "opencode") return markdown;
  // Keep relative TH method links in the same namespace as their native skill.
  return markdown.replace(/(\]\(<?(?:\.\.\/)+)find-bugs(?=\/)/g,
    (_match, prefix) => `${prefix}${projectedSkillName("find-bugs", runtime)}`);
}

