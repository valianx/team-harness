import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import test from 'node:test';

const packer = new URL('./pack-kit.mjs', import.meta.url);
test('packing is repeatable and freshness detects changed canonical payload', async (t) => {
  const root = await mkdtemp(join(tmpdir(), 'harness-pack-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const kit = join(root, 'kit');
  const vendor = join(root, 'vendor');
  await mkdir(kit);
  await writeFile(join(kit, 'package.json'), JSON.stringify({ name: 'slidev-addon-harness', version: '1.0.0', private: true, files: ['content.txt'] }));
  await writeFile(join(kit, 'content.txt'), 'first content');
  const run = (...flags) => spawnSync(process.execPath, [fileURLToPath(packer), '--kit-dir', kit, '--vendor-dir', vendor, ...flags], { encoding: 'utf8' });
  let result = run();
  assert.equal(result.status, 0, result.stderr);
  const first = await readFile(join(vendor, 'slidev-addon-harness-1.0.0.tgz'));
  result = run();
  assert.equal(result.status, 0, result.stderr);
  assert.deepEqual(await readFile(join(vendor, 'slidev-addon-harness-1.0.0.tgz')), first);
  assert.equal(run('--check').status, 0);
  const integrity = 'sha512-' + createHash('sha512').update(first).digest('base64');
  await writeFile(join(root, 'package.json'), JSON.stringify({ dependencies: { 'slidev-addon-harness': 'file:vendor/slidev-addon-harness-1.0.0.tgz' } }));
  await writeFile(join(root, 'package-lock.json'), JSON.stringify({ packages: { 'node_modules/slidev-addon-harness': { resolved: 'file:vendor/slidev-addon-harness-1.0.0.tgz', integrity: 'sha512-stale' } } }));
  result = run('--check');
  assert.notEqual(result.status, 0);
  assert.match(result.stderr, /lockfile|integrity/i);
  await writeFile(join(root, 'package-lock.json'), JSON.stringify({ packages: { 'node_modules/slidev-addon-harness': { resolved: 'file:vendor/slidev-addon-harness-1.0.0.tgz', integrity } } }));
  assert.equal(run('--check').status, 0);
  await writeFile(join(kit, 'content.txt'), 'second content');
  result = run('--check');
  assert.notEqual(result.status, 0);
  assert.match(result.stderr, /stale|fresh|differ/i);
  assert.deepEqual(await readFile(join(vendor, 'slidev-addon-harness-1.0.0.tgz')), first);
});
